export type TutorialTheme = "light" | "dark";

export type TypstPageParams = {
  width: number;
  height: number;
  marginX: number;
  marginY: number;
};

type ThemeTokens = {
  pageFill: string;
  textFill: string;
  mutedFill: string;
  tipFill: string;
  tipStroke: string;
  codeFill: string;
  codeText: string;
};

const THEME_TOKENS: Record<TutorialTheme, ThemeTokens> = {
  dark: {
    pageFill: "1a1d26",
    textFill: "e8dfd2",
    mutedFill: "aeb7c7",
    tipFill: "203a40",
    tipStroke: "7dcfff",
    codeFill: "273140",
    codeText: "ffb86c",
  },
  light: {
    pageFill: "fffdf8",
    textFill: "25221f",
    mutedFill: "6e6860",
    tipFill: "e9f3f1",
    tipStroke: "1f6f68",
    codeFill: "f2e8dc",
    codeText: "7b341e",
  },
};

export function measureTypstPage(container: HTMLElement): TypstPageParams {
  const rect = container.getBoundingClientRect();
  const width = Math.max(1, Math.floor(rect.width));
  const height = Math.max(1, Math.floor(rect.height));

  return {
    width,
    height,
    marginX: clamp(Math.round(width * 0.08), 36, 72),
    marginY: clamp(Math.round(height * 0.075), 28, 56),
  };
}

export function buildMainSource(
  source: string,
  page: TypstPageParams,
  theme: TutorialTheme,
) {
  const tokens = THEME_TOKENS[theme];

  return `// This prelude is generated by the interactive tutorial.
#set page(
  width: ${page.width}pt,
  height: ${page.height}pt,
  margin: (x: ${page.marginX}pt, y: ${page.marginY}pt),
  fill: rgb("#${tokens.pageFill}"),
)
#set text(
  font: ("Charter", "Source Han Serif SC"),
  size: 13pt,
  fill: rgb("#${tokens.textFill}"),
  lang: "zh",
  region: "cn",
)
#set par(justify: false, leading: 0.72em)
#show raw: set text(font: ("BlexMono Nerd Font Mono", "Source Han Serif SC"))

${source}`;
}

export function buildBookSource(theme: TutorialTheme) {
  const tokens = THEME_TOKENS[theme];

  return `#let chapter(title) = body => [
  #metadata((kind: "interactive-page", title: title)) <interactive-page>
  = #title
  #body
]

#let pro-tip(body) = block(
  width: 100%,
  inset: 12pt,
  fill: rgb("#${tokens.tipFill}"),
  body,
)

#show link: it => text(fill: rgb("#${tokens.tipStroke}"), it)
#let muted(body) = text(fill: rgb("#${tokens.mutedFill}"), body)
`;
}

function clamp(value: number, min: number, max: number) {
  return Math.min(Math.max(value, min), max);
}
